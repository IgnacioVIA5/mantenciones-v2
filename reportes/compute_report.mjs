      lecturaActual: e.horaActual || 0,
      lecturaFecha: e.horaActualFecha || null,
      odometro: esCamion ? (e.odometro || 0) : null,
      odometroFecha: esCamion ? (e.odometroFecha || null) : null,
      ultimaPreventivaFecha: e.ultimaPreventivaFecha || ultimaFechaHist(e.patente, "PREVENTIVA"),
      ultimaGeneralFecha: e.ultimaGeneralFecha || ultimaFechaHist(e.patente, "GENERAL"),
